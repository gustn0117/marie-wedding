// 내용을 고치면 updatedAt 도 바꾼다(구조화 데이터 dateModified·사이트맵 lastmod 에 쓰인다).
import type { BusinessType } from '@/shared/constants';

export interface LandingFact {
  label: string;
  value: string;
}

export interface LandingRole {
  name: string;
  desc: string;
  /** 관련 가이드로 이어지는 링크(있으면 카드 전체가 링크) */
  href?: string;
}

export interface LandingSection {
  /** 목차·앵커용 id(영문) */
  id: string;
  heading: string;
  body?: string[];
  /** '제목 — 설명' 형식이면 제목을 굵게 보여준다 */
  items?: string[];
  /** steps: 번호 흐름 · check: 체크리스트 · list: 점 목록 */
  itemStyle?: 'steps' | 'check' | 'list';
}

export interface Landing {
  slug: string;
  /** 이 가이드가 다루는 업종(BUSINESS_TYPES value). 빈 배열이면 전체 업종. 최신 공고·목록 링크에 쓴다. */
  businessTypes: BusinessType[];
  keywords: string[];
  title: string; // <title> (템플릿이 ' | 마리에' 부착)
  description: string;
  /** 짧은 이름 — 푸터·목록 링크 글자 */
  eyebrow: string;
  h1: string;
  /** 첫 문단 — 정의문으로 시작 */
  lead: string;
  /** 한눈에 보기 — 4개 */
  summary: LandingFact[];
  rolesHeading?: string;
  roles: LandingRole[];
  sections: LandingSection[];
  career?: { steps: string[]; note: string };
  tips: { seeker: string[]; employer: string[] };
  faq: { q: string; a: string }[];
  /** Occupation 구조화 데이터(직무 가이드만) */
  occupation?: { name: string; alternateNames: string[]; skills: string[] };
  publishedAt: string; // YYYY-MM-DD
  updatedAt: string; // YYYY-MM-DD
}

